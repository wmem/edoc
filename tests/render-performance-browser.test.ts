import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
import {readerFixture} from './reader-fixture.ts';
import {resolveProjectConfig} from '../packages/core/project.ts';
import {loadBook} from '../packages/core/book.ts';
import {compileBook,bookHTML} from '../packages/pack-html/book.ts';
import {routeHash} from '../packages/core/routes.ts';
import {waveform} from '../packages/render-wave/index.ts';
import type {Waveform} from '../packages/core/types.ts';

test('共享布局离线按文章绘制，重复图形独立交互，完整导出、折叠打印与波形保持可用',{timeout:60000},async t=>{
 const p=readerFixture(t),index=join(p.root,'fpga/docs/index.mdoc');
 p.write('fpga/docs/index.mdoc',readFileSync(index,'utf8')+'\n{% section id="extra" title="折叠图形" collapsed=true %}\n{% clause id="graph-rule" title="图形原文" %}\n{% relation-diagram id="overview" /%}\n{% waveform id="wave" /%}\n{% /clause %}\n{% /section %}\n{% waveform id="wave" /%}');
 const wave:Waveform={id:'wave',kind:'waveform',label:'请求与响应',format:'wavejson',semantic:'specification',source:{file:'docs/index.mdoc'},data:{signal:[{name:'clk',wave:'p...'},{name:'valid',wave:'01.0'},{name:'data',wave:'x3.x',data:['数据']}]}};
 p.write('fpga/docs/ir/wave.json',{waveforms:[wave]});
 const book=await loadBook(await resolveProjectConfig(join(p.root,'edoc.config.js'))),output=join(p.root,'preview.html'),html=await bookHTML(book);
 const precomputed=await compileBook(book);
 writeFileSync(output,html);
 const payload=JSON.parse(html.match(/<script id="edoc-book" type="application\/json">([\s\S]*?)<\/script>/)![1]);
 for(const page of Object.values(payload.pages) as any[])assert.doesNotMatch(page.html,/<svg\b/);
 for(const [key,value]of Object.entries(precomputed.pages))assert.deepEqual(payload.pages[key].anchorAliases,value.anchorAliases);
 const browser=await chromium.launch({executablePath:process.env.EDOC_CHROMIUM,args:['--no-sandbox']});t.after(()=>browser.close());
 const context=await browser.newContext({offline:true,viewport:{width:1440,height:1000}}),page=await context.newPage(),errors:string[]=[],requests:string[]=[];
 page.on('pageerror',error=>errors.push(error.message));page.on('request',request=>{if(/^https?:/.test(request.url()))requests.push(request.url());});
 await page.goto(pathToFileURL(output).href+routeHash({kind:'page',project:'fpga',id:'docs/index'}));await page.waitForFunction(()=>window.EdocReady);
 assert.equal(await page.locator('.static-svg svg').count(),2);assert.equal(await page.locator('.wave svg').count(),2);
 const alias=payload.pages[JSON.stringify(['fpga','docs/index'])]?.anchorAliases?.['edoc-wave-0-wavelane_0_0'];
 assert.ok(alias);assert.equal(await page.locator('[id="'+alias+'"]').count(),1);
 const expected=(waveform(wave,0).match(/<path\b/g)??[]).length;
 assert.equal(await page.locator('.wave').first().locator('path').count(),expected);
 assert.equal(await page.evaluate(()=>{const ids=[...document.querySelectorAll('#reader svg [id]')].map(e=>e.id);return ids.length-new Set(ids).size;}),0);
 const first=page.locator('[data-diagram]').first();await first.scrollIntoViewIfNeeded();
 await first.getByRole('button',{name:'全部展开',exact:true}).click();await page.waitForFunction(()=>window.EdocInterfaceViews[0].holder.dataset.busy==='false');
 await page.locator('#reader details').filter({has:page.locator('summary', {hasText:'折叠图形'})}).locator('summary').first().click();
 const second=page.locator('[data-diagram]').nth(1);await second.scrollIntoViewIfNeeded();await page.waitForFunction(()=>window.EdocInterfaceViews.length===2);
 assert.equal(await page.evaluate(()=>window.EdocInterfaceViews[1].state.modes.bus),'collapsed');
 const pending=page.waitForEvent('download');await second.getByRole('button',{name:'SVG（逐信号）',exact:true}).click();const download=await pending;
 const svg=readFileSync((await download.path())!,'utf8');assert.match(svg,/device.out/);assert.match(svg,/memory.in/);assert.match(svg,/@font-face/);
 await page.emulateMedia({media:'print'});assert.equal(await second.locator('.static-svg svg').isVisible(),true);await page.emulateMedia({media:'screen'});
 await page.goto(pathToFileURL(output).href+routeHash({kind:'page',project:'board',id:'docs/index'}));await page.waitForFunction(()=>window.EdocReady);assert.match(await page.locator('.static-svg').textContent()??'',/BOARD DEVICE/);
 assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
});
