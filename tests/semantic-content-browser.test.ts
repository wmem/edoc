import test from 'node:test';
import {mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
import {loadBook} from '../packages/core/book.ts';
import {resolveProjectConfig} from '../packages/core/project.ts';
import {bookHTML} from '../packages/pack-html/book.ts';
import {repository} from './helpers.ts';
import {anchor} from '../packages/core/identity.ts';

test('语义合同离线导航：原文返回、折叠定位、只读复用与窄屏',{timeout:60000},async t=>{
 const root=mkdtempSync(join(tmpdir(),'edoc-contract-browser-'));t.after(()=>rmSync(root,{recursive:true,force:true}));
 const book=await loadBook(await resolveProjectConfig(join(repository,'examples/behavior-contract/docs/edoc.config.js'))),file=join(root,'index.html');
 writeFileSync(file,await bookHTML(book));
 const browser=await chromium.launch({executablePath:process.env.EDOC_CHROMIUM,args:['--no-sandbox']});t.after(()=>browser.close());
 const context=await browser.newContext({offline:true,viewport:{width:1440,height:1000}}),page=await context.newPage();
 const check=(ok:boolean,msg:string)=>{if(!ok)throw new Error(msg);};
 const ready=()=>page.waitForFunction(()=>window.EdocReady);
 const behavior=page.locator('#'+anchor('demo:timeout'));
 const late=page.locator('#'+anchor('demo:late-completion'));
 const shared=behavior.locator('[data-clause="demo:one-result"]');
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(file).href);await ready();
 await page.locator('#toc').getByRole('link',{name:'异步发送',exact:true}).click();await ready();
 check(!(await late.evaluate(d=>(d as HTMLDetailsElement).open)),'边界子节应默认折叠');
 await shared.locator(':scope > summary').click();
 const hash=await page.evaluate(()=>location.hash);
 await shared.getByRole('link',{name:'条款原文',exact:true}).click();await ready();
 check(await page.locator('#reader [data-clause="demo:one-result"]').count()===1,'应定位唯一原文');
 check(await page.locator('#reader [data-clause="demo:one-result"]').evaluate(d=>(d as HTMLDetailsElement).open),'原文条款应自动展开');
 await page.getByRole('button',{name:'返回',exact:true}).click();await ready();
 check(await page.evaluate(()=>location.hash)===hash,'返回恢复来源页');
 check(await shared.evaluate(d=>(d as HTMLDetailsElement).open),'返回恢复引用条款展开');
 check(!(await late.evaluate(d=>(d as HTMLDetailsElement).open)),'返回保留边界折叠');
 await page.locator('#search').fill('demo:late-isolation');
 await page.locator('#results a').filter({hasText:'旧请求不得影响新请求'}).click();await ready();
 check(await late.evaluate(d=>(d as HTMLDetailsElement).open),'搜索条款应打开折叠祖先');
 check(await page.locator('#reader [data-clause="demo:late-isolation"]').evaluate(d=>(d as HTMLDetailsElement).open),'目标条款应打开');
 const duplicates=await page.locator('#reader').evaluate(r=>{const ids=[...r.querySelectorAll('[id]')].map(e=>e.id);return ids.filter((id,i)=>ids.indexOf(id)!==i);});
 check(duplicates.length===0,'重复 DOM 锚点');
 await page.locator('[data-reading-scope="clause"]').getByRole('button',{name:'折叠条款',exact:true}).click();
 check(await late.evaluate(d=>(d as HTMLDetailsElement).open),'条款折叠不应改变章节折叠');
 await page.locator('#toc').getByRole('link',{name:'沿行为审阅合同',exact:true}).click();await ready();
 check(await page.locator('#reader [data-clause="demo:one-result"]').count()===1,'审阅页只读复用');
 await page.locator('#reader [data-clause="demo:one-result"]').getByRole('link',{name:'条款原文',exact:true}).click();await ready();
 await page.locator('#reader').getByRole('link',{name:'发送超时',exact:true}).click();await ready();
 check(await behavior.evaluate(d=>(d as HTMLDetailsElement).open),'条款反向链接打开行为');
 await page.setViewportSize({width:390,height:844});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'窄屏溢出');
 check(errors.length===0,errors.join('\n'));
});
